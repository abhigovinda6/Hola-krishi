"use client";
import { useEffect, useState } from "react";
import { useApp, farmToPayload } from "./AppState";
import { t } from "@/lib/i18n";
import { fetchSummary, type Summary as S } from "@/lib/summary_cache";


export default function AiSummary({ focus }: { focus?: string }) {
  const { farm, ready, lang, qs } = useApp();
  const [s, setS] = useState<S | null>(null); const [busy, setBusy] = useState(false);
  useEffect(() => {
    if (!ready) return; let live = true; setBusy(true); setS(null);
    fetchSummary(JSON.stringify({ ...farmToPayload(farm), lang, focus }))
      .then((v) => live && setS(v)).finally(() => live && setBusy(false));
    return () => { live = false; };
  }, [qs, lang, focus, ready]); // eslint-disable-line
  return (
    <section className="card ai" data-testid="ai-summary">
      <div className="aihead"><h3>✦ {t("ai_title", lang)}</h3><span className="badge">{t("ai_badge", lang)}</span></div>
      {busy && <div className="skel" aria-busy="true"><span /><span /><span /><em>{t("ai_loading", lang)}</em></div>}
      {s && "error" in s && <p className="err">Couldn&apos;t create a summary: {s.error}</p>}
      {s && !("error" in s) && (<>
        {s.source === "template" && <p className="note">{t("ai_fallback", lang)}</p>}
        <div className="aitext" data-source={s.source}>{s.text.split(/\n+/).map((p, i) => <p key={i}>{p}</p>)}</div>
        {s.source === "llm" && <p className="meta">Generated by {s.provider} ({s.model}). Check the numbers in the table: the AI only rephrases them.</p>}
      </>)}
    </section>
  );
}
